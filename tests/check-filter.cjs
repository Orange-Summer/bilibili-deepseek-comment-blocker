const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})});
  try {
    const page = await browser.newPage();
    await page.setContent('<bili-comments></bili-comments>');
    await page.evaluate(() => {
      window.__consoleLogs = [];
      const nativeInfo = console.info.bind(console);
      console.info = (...args) => { window.__consoleLogs.push(args); nativeInfo(...args); };
      window.GM_getValue = (_, fallback) => ({ ...fallback, allowedUIDs: ['456'] });
      window.GM_setValue = (_, value) => { window.__savedConfig = value; };
      window.GM_registerMenuCommand = () => {};
      const container = document.querySelector('bili-comments').attachShadow({mode:'open'});
      const thread = document.createElement('bili-comment-thread-renderer');
      container.append(thread);
      const threadRoot = thread.attachShadow({mode:'open'});
      window.makeItem = (uid, name, text, parent = threadRoot, type = 'bili-comment-renderer') => {
        const item = document.createElement(type); item.style.display = 'block'; parent.append(item);
        const root = item.attachShadow({mode:'open'});
        const body = document.createElement('div'); body.id = 'body'; body.style.cssText = 'padding:12px 0 20px 56px;border-bottom:1px solid #eee'; root.append(body);
        const author = document.createElement('bili-comment-user-info'); body.append(author);
        const ar = author.attachShadow({mode:'open'});
        const a = document.createElement('a'); a.id='user-name'; a.href='https://space.bilibili.com/'+uid; a.textContent=name; ar.append(a);
        const rich = document.createElement('bili-rich-text'); body.append(rich); rich.style.cssText = 'display:block;margin:8px 0';
        const rr = rich.attachShadow({mode:'open'});
        const contents = document.createElement('div'); contents.id='contents'; contents.textContent=text; rr.append(contents);
        const actions = document.createElement('bili-comment-action-buttons-renderer'); body.append(actions);
        actions.attachShadow({mode:'open'}).innerHTML = '<style>#actions{display:flex;align-items:center;gap:16px;color:#9499a0;font:12px/24px sans-serif}</style><div id="actions"><span id="like">赞</span><span id="reply">回复</span></div>';
        return item;
      };
      window.findUI = item => item.shadowRoot.querySelector('[data-baf-ui]') || item.shadowRoot.querySelector('bili-comment-action-buttons-renderer')?.shadowRoot.querySelector('[data-baf-ui]');
      window.normal = makeItem('123', '鱼丸', '回复 @鲸鱼: @朋友 这个视频不错——真的！');
      window.suspect = makeItem('456', '某人的大肥鱼', '本鱼也这么觉得');
      window.reply = makeItem('789', '真人', '我是正常楼中楼', threadRoot, 'bili-comment-reply-renderer');
    });
    let source = fs.readFileSync(path.join(__dirname, '..', 'bilibili-deepseek-comment-blocker.user.js'),'utf8');
    source = source.replace('  // 兜底', '  window.__test = { classify, validate, read, scan, save, defaults: DEFAULTS };\n  // 兜底');
    await page.addScriptTag({content:source});
    const results = await page.evaluate(async () => {
      const t = __test, c = t.defaults;
      const result = [];
      const check = (name, ok) => result.push([name,!!ok]);
      const initialLog = window.__consoleLogs.find(entry => entry[0] === '[B站评论屏蔽]');
      check('startup console reports enabled state and blacklist count', initialLog?.[1] === '脚本已启用' && initialLog[2].状态 === '已启用' && initialLog[2].黑名单数量 === 0);
      check('startup console reports current page fold count', initialLog?.[2].页面当前折叠 === 1);
      check('normal @, punctuation and fish name retained', !normal.hasAttribute('data-baf-fold'));
      check('combined persona signals folded', suspect.hasAttribute('data-baf-fold'));
      check('reply retained when root folded', !reply.hasAttribute('data-baf-fold') && reply.isConnected);
      check('author UID and name read from shadow', t.read(suspect).uid==='456' && t.read(suspect).name==='某人的大肥鱼');
      const nativeActions = item => item.shadowRoot.querySelector('bili-comment-action-buttons-renderer').shadowRoot;
      check('controls follow reply in current comment', findUI(normal).previousElementSibling === nativeActions(normal).querySelector('#reply'));
      check('controls visually align with current reply', Math.abs(findUI(normal).getBoundingClientRect().top - nativeActions(normal).querySelector('#reply').getBoundingClientRect().top) < 8);
      check('folded summary remains visible outside hidden body', findUI(suspect).parentNode === suspect.shadowRoot && findUI(suspect).getBoundingClientRect().height > 0);
      const record = {uid:'456',name:'某人的大肥鱼',text:'本鱼来了'};
      check('legacy exemptions do not bypass blacklist', t.classify(record,{...c,blockedUIDs:['456'],allowedUIDs:['456']}).fold);
      check('legacy fields stripped on import', !Object.hasOwn(t.validate({...c,allowedUIDs:['456']}),'allowedUIDs'));
      check('legacy fields cleared from stored config', window.__savedConfig && !Object.hasOwn(window.__savedConfig,'allowedUIDs'));
      check('trust button removed', ![...findUI(suspect).querySelectorAll('button')].some(b=>b.textContent.includes('信任')));
      check('observe does not fold blacklist', !t.classify(record,{...c,mode:'observe',blockedUIDs:['456']}).fold);
      check('nickname alone only marks', !t.classify({...record,text:'普通内容'}).fold);
      check('strict folds weak signal', t.classify({...record,text:'普通内容'},{...c,mode:'strict'}).fold);
      check('disabled retains all', !t.classify(record,{...c,enabled:false,blockedUIDs:['456']}).fold);
      check('reply prefix does not trigger phrase', !t.classify({uid:'123',name:'真人',text:'回复 @本鱼: 好的'},{...c,blockedPhrases:['本鱼']}).fold);
      check('custom phrase normalized', t.classify({uid:'123',name:'真人',text:'ＡＢＣ'},{...c,blockedPhrases:['abc']}).fold);
      let invalid=false; try { t.validate({...c,blockedUIDs:[123]}); } catch(e) {invalid=true;}
      check('numeric UID rejected',invalid);
      const toggle = [...findUI(suspect).querySelectorAll('button')].find(b=>b.textContent==='展开原文');
      toggle.click(); t.scan();
      check('expand original', !suspect.hasAttribute('data-baf-fold'));
      check('expanded controls return to current action row', findUI(suspect).parentNode === nativeActions(suspect).querySelector('#actions'));
      t.save({...c,blockedUIDs:['123']}); t.scan();
      check('blacklist re-evaluates loaded comments', normal.hasAttribute('data-baf-fold'));
      t.save({...c,enabled:false,blockedUIDs:['123']}); t.scan();
      await new Promise(resolve => setTimeout(resolve, 650));
      const pauseLog = window.__consoleLogs.at(-1);
      check('pause console reflects preserved blacklist and unfolded page', pauseLog[1] === '已暂停过滤' && pauseLog[2].状态 === '已暂停' && pauseLog[2].黑名单数量 === 1 && pauseLog[2].页面当前折叠 === 0);
      check('pause restores loaded comments', !normal.hasAttribute('data-baf-fold') && !suspect.hasAttribute('data-baf-fold'));
      const findButton = (item, label) => [...findUI(item).querySelectorAll('button')].find(b => b.textContent === label);
      const removeWhilePaused = findButton(normal, '移出黑名单');
      check('pause keeps removal button', !!removeWhilePaused);
      check('pause keeps block button', !!findButton(suspect, '屏蔽此 UID'));
      removeWhilePaused?.click(); t.scan();
      check('paused removal persists without resuming', !window.__savedConfig.blockedUIDs.includes('123') && !window.__savedConfig.enabled);
      const blockWhilePaused = findButton(normal, '屏蔽此 UID');
      check('paused removal switches to block button', !!blockWhilePaused);
      blockWhilePaused?.click(); t.scan();
      check('paused addition persists without folding', window.__savedConfig.blockedUIDs.includes('123') && !window.__savedConfig.enabled && !normal.hasAttribute('data-baf-fold'));
      t.save({...window.__savedConfig,enabled:true}); t.scan();
      await new Promise(resolve => setTimeout(resolve, 650));
      const resumeLog = window.__consoleLogs.at(-1);
      check('resume console reflects enabled state and current fold count', resumeLog[1] === '已恢复过滤' && resumeLog[2].状态 === '已启用' && resumeLog[2].页面当前折叠 === 2);
      check('resume applies blacklist edited during pause', normal.hasAttribute('data-baf-fold'));
      t.save(c); t.scan();
      normal.shadowRoot.querySelector('bili-comment-action-buttons-renderer').remove(); t.scan();
      check('missing native actions falls back below own text', findUI(normal).previousElementSibling === normal.shadowRoot.querySelector('bili-rich-text'));
      const replacementActions = document.createElement('bili-comment-action-buttons-renderer');
      replacementActions.attachShadow({mode:'open'}).innerHTML = '<div id="actions"><span id="reply">回复</span></div>';
      normal.shadowRoot.querySelector('#body').append(replacementActions); t.scan();
      check('controls follow rebuilt native action row', findUI(normal).previousElementSibling === replacementActions.shadowRoot.querySelector('#reply'));
      const label = suspect.shadowRoot.querySelector('[data-baf-ui]');
      await new Promise(r=>setTimeout(r,800));
      check('observer render converges', label === suspect.shadowRoot.querySelector('[data-baf-ui]'));
      const logCount = window.__consoleLogs.length;
      t.scan(); t.scan();
      await new Promise(resolve => setTimeout(resolve, 650));
      check('unchanged scans do not spam console', window.__consoleLogs.length === logCount);
      return result;
    });
    for (const [name, ok] of results) { console.log((ok?'PASS ':'FAIL ')+name); assert(ok,name); }
    console.log(results.length+' checks passed; synthetic DOM only.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
